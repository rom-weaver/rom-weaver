//! GBA GameShark and Action Replay ROM-patch decoders.
//!
//! The instruction layouts, initial TEA keys, and reseed tables follow mGBA's
//! format definitions:
//! <https://github.com/mgba-emu/mgba/tree/master/src/gba/cheats>.

use rom_weaver_core::Result;

use super::{CheatKind, CheatSystem, DecodedCode, coded};

const GAMESHARK_SEEDS: [u32; 4] = [0x09F4_FBBD, 0x9681_884A, 0x3520_27E9, 0xF3DE_E5A7];
const ACTION_REPLAY_SEEDS: [u32; 4] = [0x7AA9_648F, 0x7FAE_6994, 0xC0EF_AAD5, 0x4271_2C57];

#[derive(Clone, Copy)]
enum Format {
    GameShark,
    ActionReplay,
}

pub(super) fn decode_codes(input: &str, kind: CheatKind) -> Result<Vec<DecodedCode>> {
    let (format, encrypted, mut seeds) = match kind {
        CheatKind::GameSharkV1 => (Format::GameShark, true, GAMESHARK_SEEDS),
        CheatKind::GameSharkV1Raw => (Format::GameShark, false, GAMESHARK_SEEDS),
        CheatKind::ActionReplayV3 => (Format::ActionReplay, true, ACTION_REPLAY_SEEDS),
        CheatKind::ActionReplayV3Raw => (Format::ActionReplay, false, ACTION_REPLAY_SEEDS),
        _ => {
            return Err(unsupported(
                input,
                "this is not a GBA GameShark or Action Replay code kind",
            ));
        }
    };
    let words = parse_words(input)?;
    if words.is_empty() || !words.len().is_multiple_of(2) {
        return Err(bad(
            input,
            "GBA GameShark and Action Replay codes need pairs of eight-digit words",
        ));
    }

    let mut decoded = Vec::new();
    let mut pending_patch = None;
    for pair in words.chunks_exact(2) {
        let (mut op1, mut op2) = (pair[0], pair[1]);
        if encrypted {
            decrypt(&mut op1, &mut op2, &seeds);
        }
        match format {
            Format::GameShark => decode_gameshark(op1, op2, kind, &mut seeds, &mut decoded, input)?,
            Format::ActionReplay => decode_action_replay(
                op1,
                op2,
                kind,
                &mut seeds,
                &mut pending_patch,
                &mut decoded,
                input,
            )?,
        }
    }
    if pending_patch.is_some() {
        return Err(bad(
            input,
            "the Action Replay ROM patch is missing its value line",
        ));
    }
    if decoded.is_empty() {
        return Err(unsupported(
            input,
            "the code list contains no ROM patch writes",
        ));
    }
    Ok(decoded)
}

fn parse_words(input: &str) -> Result<Vec<u32>> {
    let mut words = Vec::new();
    for group in input
        .split(|c: char| c.is_whitespace() || matches!(c, '+' | ',' | ';' | ':' | '-'))
        .filter(|word| !word.is_empty())
    {
        if !group.len().is_multiple_of(8) || !group.bytes().all(|byte| byte.is_ascii_hexdigit()) {
            return Err(bad(
                input,
                "each GBA GameShark or Action Replay word must have eight hexadecimal digits",
            ));
        }
        for chunk in group.as_bytes().chunks_exact(8) {
            let word = std::str::from_utf8(chunk)
                .map_err(|_| bad(input, "the code contains invalid hexadecimal"))?;
            words.push(
                u32::from_str_radix(word, 16)
                    .map_err(|_| bad(input, "the code contains invalid hexadecimal"))?,
            );
        }
    }
    Ok(words)
}

fn decode_gameshark(
    op1: u32,
    op2: u32,
    kind: CheatKind,
    seeds: &mut [u32; 4],
    decoded: &mut Vec<DecodedCode>,
    raw: &str,
) -> Result<()> {
    if op1 == 0xDEAD_FACE {
        reseed(seeds, op2 as u16, GAMESHARK_T1, GAMESHARK_T2);
        return Ok(());
    }
    if op1 >> 28 != 6 {
        return Err(unsupported(
            raw,
            "the GameShark list contains a runtime, conditional, button, or hook code",
        ));
    }
    if op2 > u32::from(u16::MAX) {
        return Err(unsupported(
            raw,
            "the GameShark ROM patch has nonzero bits outside its halfword value",
        ));
    }
    decoded.push(patch(kind, op1 & 0x00FF_FFFF, op2));
    Ok(())
}

fn decode_action_replay(
    op1: u32,
    op2: u32,
    kind: CheatKind,
    seeds: &mut [u32; 4],
    pending_patch: &mut Option<u32>,
    decoded: &mut Vec<DecodedCode>,
    raw: &str,
) -> Result<()> {
    if let Some(offset) = pending_patch.take() {
        if op1 > u32::from(u16::MAX) || op2 != 0 {
            return Err(unsupported(
                raw,
                "the Action Replay ROM patch value line has nonzero reserved bits",
            ));
        }
        decoded.push(patch(kind, offset, op1));
        return Ok(());
    }
    if op1 == 0xDEAD_FACE {
        reseed(seeds, op2 as u16, ACTION_REPLAY_T1, ACTION_REPLAY_T2);
        return Ok(());
    }
    if (op1 == 0 && op2 == 0) || op2 == 0x001D_C0DE {
        return Ok(());
    }
    if op1 == 0 && matches!(op2 >> 24, 0x18 | 0x1A | 0x1C | 0x1E) {
        *pending_patch = Some(op2 & 0x00FF_FFFF);
        return Ok(());
    }
    Err(unsupported(
        raw,
        "the Action Replay list contains a runtime, conditional, button, fill, or hook code",
    ))
}

fn patch(kind: CheatKind, halfword_offset: u32, value: u32) -> DecodedCode {
    DecodedCode {
        system: CheatSystem::GameBoyAdvance,
        kind,
        address: 0x0800_0000u32.saturating_add(halfword_offset.saturating_mul(2)),
        value,
        compare: None,
        width: 2,
    }
}

fn decrypt(op1: &mut u32, op2: &mut u32, seeds: &[u32; 4]) {
    let mut sum = 0xC6EF_3720u32;
    for _ in 0..32 {
        *op2 = op2.wrapping_sub(
            (op1.wrapping_shl(4).wrapping_add(seeds[2]))
                ^ op1.wrapping_add(sum)
                ^ (op1.wrapping_shr(5).wrapping_add(seeds[3])),
        );
        *op1 = op1.wrapping_sub(
            (op2.wrapping_shl(4).wrapping_add(seeds[0]))
                ^ op2.wrapping_add(sum)
                ^ (op2.wrapping_shr(5).wrapping_add(seeds[1])),
        );
        sum = sum.wrapping_sub(0x9E37_79B9);
    }
}

fn reseed(seeds: &mut [u32; 4], params: u16, table1: &[u8; 256], table2: &[u8; 256]) {
    let s0 = usize::from(params >> 8);
    let s1 = usize::from(params & 0xFF);
    for (y, seed) in seeds.iter_mut().enumerate() {
        for x in 0..4 {
            let byte = table1[(s0 + x) & 0xFF].wrapping_add(table2[(s1 + y) & 0xFF]);
            *seed = seed.wrapping_shl(8) | u32::from(byte);
        }
    }
}

fn bad(raw: &str, message: &'static str) -> rom_weaver_core::RomWeaverError {
    coded("cheat_bad_code", message, raw)
}

fn unsupported(raw: &str, message: &'static str) -> rom_weaver_core::RomWeaverError {
    coded("cheat_unsupported_code", message, raw)
}

